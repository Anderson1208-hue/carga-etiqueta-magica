CREATE TABLE public.ordens_coleta (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  data_coleta date NOT NULL DEFAULT (timezone('America/Sao_Paulo', now()))::date,
  hora_prevista time,
  embarcador_id uuid REFERENCES public.embarcadores(id) ON DELETE RESTRICT,
  embarcador_nome text NOT NULL,
  endereco text NOT NULL,
  cidade text,
  uf text CHECK (uf IS NULL OR uf ~ '^[A-Z]{2}$'),
  contato text,
  telefone text,
  motorista text,
  placa text CHECK (placa IS NULL OR placa ~ '^[A-Z0-9]{7}$'),
  notas_fiscais text,
  volumes integer NOT NULL DEFAULT 0 CHECK (volumes >= 0),
  peso_kg numeric(14,3) NOT NULL DEFAULT 0 CHECK (peso_kg >= 0),
  observacoes text,
  status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'agendada', 'em_coleta', 'coletada', 'cancelada')),
  created_by uuid DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE ON public.ordens_coleta TO authenticated;
GRANT ALL ON public.ordens_coleta TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.ordens_coleta_numero_seq TO authenticated;
GRANT ALL ON SEQUENCE public.ordens_coleta_numero_seq TO service_role;

ALTER TABLE public.ordens_coleta ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Operadores ativos consultam ordens de coleta"
  ON public.ordens_coleta FOR SELECT TO authenticated
  USING ((SELECT public.is_active_operator()));

CREATE POLICY "Operadores ativos criam ordens de coleta"
  ON public.ordens_coleta FOR INSERT TO authenticated
  WITH CHECK ((SELECT public.is_active_operator()) AND created_by = auth.uid());

CREATE POLICY "Operadores ativos editam ordens de coleta"
  ON public.ordens_coleta FOR UPDATE TO authenticated
  USING ((SELECT public.is_active_operator()))
  WITH CHECK ((SELECT public.is_active_operator()));

CREATE INDEX ordens_coleta_data_numero_idx ON public.ordens_coleta (data_coleta DESC, numero DESC);
CREATE INDEX ordens_coleta_status_data_idx ON public.ordens_coleta (status, data_coleta DESC);

CREATE FUNCTION public.ordens_coleta_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER ordens_coleta_touch_updated_at
  BEFORE UPDATE ON public.ordens_coleta
  FOR EACH ROW EXECUTE FUNCTION public.ordens_coleta_touch_updated_at();